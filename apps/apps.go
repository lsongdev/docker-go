// Package apps installs and manages catalog apps as compose projects.
//
// Each installed app lives in its own directory:
//
//	<root>/<id>/compose.yaml  the app's compose template
//	<root>/<id>/runtime.compose.yaml  resources templates expect the host
//	                          to provide (merged after compose.yaml)
//	<root>/<id>/.env          every variable the template needs
//	<root>/<id>/app.json      the install record (version, port, settings)
//	<root>/<id>/data/...      seed files and the app's persistent data
//
// The compose project name is the app id. Because the environment is stored
// in .env, the plain docker compose CLI works on an installed app too.
package apps

import (
	"cmp"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"maps"
	"net"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
	"sync"
	"time"

	"github.com/lsongdev/docker-go/catalog"
	"github.com/lsongdev/docker-go/compose"
	"github.com/lsongdev/docker-go/engine"
)

var (
	ErrNotInstalled = errors.New("app is not installed")
	ErrInstalled    = errors.New("app is already installed")
	ErrUnavailable  = errors.New("app cannot be installed")
)

const (
	recordFile  = "app.json"
	composeFile = "compose.yaml"
	runtimeFile = "runtime.compose.yaml"
	envFile     = ".env"
	// projectLabel is set by compose on every container of a project.
	projectLabel = "com.docker.compose.project"
)

// runtimeCompose declares what catalog templates rely on the host for:
// templates attach services to "default_network" but need not declare it.
// A template that does declare it uses this same definition, so the merge
// is a no-op.
const runtimeCompose = `# Generated by docker-go. Declares resources app templates expect the
# host to provide; merged after compose.yaml.
networks:
  default_network:
    driver: bridge
`

// Settings are host-wide values exposed to every app template.
type Settings struct {
	Host             string // address users reach apps at, e.g. 192.168.1.10
	LocalDomain      string // LOCAL_DOMAIN
	Timezone         string // TZ
	StorageDir       string // ROOT_FOLDER_HOST: shared media/storage root
	DNSIP            string // DNS_IP
	NetworkInterface string // NETWORK_INTERFACE
	Arch             string // amd64, arm64; empty asks the daemon
}

// Manager installs and operates apps.
type Manager struct {
	root     string
	catalog  *catalog.Catalog
	cli      *compose.CLI
	engine   *engine.Client
	settings Settings

	archMu sync.Mutex
	arch   string // cached daemon architecture
}

func NewManager(root string, cat *catalog.Catalog, cli *compose.CLI, eng *engine.Client, settings Settings) *Manager {
	settings.Host = cmp.Or(settings.Host, "localhost")
	settings.LocalDomain = cmp.Or(settings.LocalDomain, "local")
	settings.Timezone = cmp.Or(settings.Timezone, "UTC")
	settings.DNSIP = cmp.Or(settings.DNSIP, "9.9.9.9")
	settings.NetworkInterface = cmp.Or(settings.NetworkInterface, "eth0")
	return &Manager{root: root, catalog: cat, cli: cli, engine: eng, settings: settings}
}

// Record is the persisted install record of an app.
type Record struct {
	ID          string            `json:"id"`
	Version     string            `json:"version"`
	Port        int               `json:"port"`
	Values      map[string]string `json:"values"`
	InstalledAt time.Time         `json:"installed_at"`
	UpdatedAt   time.Time         `json:"updated_at"`
}

type Status string

const (
	StatusRunning Status = "running" // every container running
	StatusPartial Status = "partial" // some containers running
	StatusStopped Status = "stopped" // containers exist, none running
	StatusMissing Status = "missing" // installed but no containers
)

// Container is a container belonging to an app.
type Container struct {
	ID      string `json:"id"`
	Name    string `json:"name"`
	Service string `json:"service"`
	Image   string `json:"image"`
	State   string `json:"state"`
	Status  string `json:"status"`
}

// Installed is an installed app with its live state.
type Installed struct {
	Record
	App             *catalog.App `json:"app,omitempty"` // nil if no longer in the catalog
	Status          Status       `json:"status"`
	Containers      []Container  `json:"containers"`
	LatestVersion   string       `json:"latest_version,omitempty"`
	UpdateAvailable bool         `json:"update_available"`
	URL             string       `json:"url,omitempty"`
	Dir             string       `json:"dir"`
}

func (m *Manager) dir(id string) string { return filepath.Join(m.root, id) }

// Arch returns the daemon's architecture in catalog terms (amd64, arm64).
func (m *Manager) Arch(ctx context.Context) (string, error) {
	m.archMu.Lock()
	defer m.archMu.Unlock()
	if m.arch == "" {
		if m.settings.Arch != "" {
			m.arch = m.settings.Arch
		} else {
			v, err := m.engine.Version(ctx)
			if err != nil {
				return "", err
			}
			m.arch = v.Arch
		}
	}
	return m.arch, nil
}

func (m *Manager) readRecord(id string) (*Record, error) {
	if !validID(id) {
		return nil, fmt.Errorf("%w: %s", ErrNotInstalled, id)
	}
	data, err := os.ReadFile(filepath.Join(m.dir(id), recordFile))
	if os.IsNotExist(err) {
		return nil, fmt.Errorf("%w: %s", ErrNotInstalled, id)
	}
	if err != nil {
		return nil, err
	}
	var r Record
	if err := json.Unmarshal(data, &r); err != nil {
		return nil, fmt.Errorf("%s: %w", recordFile, err)
	}
	r.ID = id
	return &r, nil
}

// validID rejects ids that could escape the apps root.
func validID(id string) bool {
	return id != "" && id != "." && id != ".." && !strings.ContainsAny(id, `/\`) && compose.ValidateName(id) == nil
}

// List returns every installed app, sorted by id.
func (m *Manager) List(ctx context.Context) ([]Installed, error) {
	entries, err := os.ReadDir(m.root)
	if err != nil && !os.IsNotExist(err) {
		return nil, err
	}
	containers, err := m.containers(ctx, "")
	if err != nil {
		return nil, err
	}
	out := []Installed{}
	for _, entry := range entries {
		if !entry.IsDir() {
			continue
		}
		record, err := m.readRecord(entry.Name())
		if err != nil {
			continue
		}
		out = append(out, m.describe(*record, containers[record.ID]))
	}
	return out, nil
}

// Get returns one installed app.
func (m *Manager) Get(ctx context.Context, id string) (*Installed, error) {
	record, err := m.readRecord(id)
	if err != nil {
		return nil, err
	}
	containers, err := m.containers(ctx, id)
	if err != nil {
		return nil, err
	}
	installed := m.describe(*record, containers[id])
	return &installed, nil
}

// IsInstalled reports whether app id has an install record.
func (m *Manager) IsInstalled(id string) bool {
	_, err := m.readRecord(id)
	return err == nil
}

// containers groups compose containers by project, optionally for one project.
func (m *Manager) containers(ctx context.Context, project string) (map[string][]Container, error) {
	filter := projectLabel
	if project != "" {
		filter += "=" + project
	}
	list, err := m.engine.ListContainers(ctx, engine.ListContainersOptions{All: true, Filters: engine.Filters{"label": {filter}}})
	if err != nil {
		return nil, err
	}
	out := map[string][]Container{}
	for _, c := range list {
		p := c.Labels[projectLabel]
		out[p] = append(out[p], Container{ID: c.ID, Name: c.Name(), Service: c.Labels["com.docker.compose.service"], Image: c.Image, State: c.State, Status: c.Status})
	}
	return out, nil
}

func (m *Manager) describe(record Record, containers []Container) Installed {
	slices.SortFunc(containers, func(a, b Container) int { return strings.Compare(a.Name, b.Name) })
	installed := Installed{Record: record, Containers: containers, Dir: m.dir(record.ID)}
	if installed.Containers == nil {
		installed.Containers = []Container{}
	}
	running := 0
	for _, c := range containers {
		if c.State == "running" {
			running++
		}
	}
	switch {
	case len(containers) == 0:
		installed.Status = StatusMissing
	case running == len(containers):
		installed.Status = StatusRunning
	case running > 0:
		installed.Status = StatusPartial
	default:
		installed.Status = StatusStopped
	}
	if app, err := m.catalog.Get(record.ID); err == nil {
		installed.App = app
		installed.LatestVersion = app.Version
		installed.UpdateAvailable = app.Version != "" && app.Version != record.Version
		if !app.NoGUI && record.Port > 0 {
			scheme := "http"
			if app.HTTPS {
				scheme = "https"
			}
			installed.URL = scheme + "://" + net.JoinHostPort(m.settings.Host, strconv.Itoa(record.Port)) + app.URLSuffix
		}
	}
	return installed
}

// Request carries user choices for an install or reconfiguration.
type Request struct {
	Port   int               `json:"port,omitempty"` // 0 keeps the current or default port
	Values map[string]string `json:"values,omitempty"`
}

// Plan is a validated install or update, ready to apply.
type Plan struct {
	App     *catalog.App
	Record  Record
	Fresh   bool // true for a new install
	compose []byte
}

// PlanInstall validates a new install of app id.
func (m *Manager) PlanInstall(ctx context.Context, id string, req Request) (*Plan, error) {
	app, err := m.catalog.Get(id)
	if err != nil {
		return nil, err
	}
	if app.Deprecated {
		return nil, fmt.Errorf("%w: %s is deprecated", ErrUnavailable, app.Name)
	}
	if m.IsInstalled(id) {
		return nil, fmt.Errorf("%w: %s", ErrInstalled, id)
	}
	now := time.Now().UTC()
	return m.plan(ctx, app, Record{ID: id, InstalledAt: now}, req, true)
}

// PlanUpdate validates moving an installed app to the catalog's current
// template, optionally with new settings. Omitted settings keep their
// current values; generated secrets are always preserved.
func (m *Manager) PlanUpdate(ctx context.Context, id string, req Request) (*Plan, error) {
	record, err := m.readRecord(id)
	if err != nil {
		return nil, err
	}
	app, err := m.catalog.Get(id)
	if err != nil {
		return nil, err
	}
	return m.plan(ctx, app, *record, req, false)
}

func (m *Manager) plan(ctx context.Context, app *catalog.App, record Record, req Request, fresh bool) (*Plan, error) {
	arch, err := m.Arch(ctx)
	if err != nil {
		return nil, err
	}
	if !app.SupportsArch(arch) {
		return nil, fmt.Errorf("%w: %s does not support %s", ErrUnavailable, app.Name, arch)
	}
	port := cmp.Or(req.Port, record.Port, app.Port)
	if port < 0 || port > 65535 {
		return nil, catalog.FieldErrors{"port": "must be between 1 and 65535"}
	}
	if port != 0 && port != record.Port {
		if owner, err := m.portOwner(ctx, port, app.ID); err != nil {
			return nil, err
		} else if owner != "" {
			return nil, catalog.FieldErrors{"port": fmt.Sprintf("port %d is already used by %s", port, owner)}
		}
	}
	input := req.Values
	if input == nil {
		input = map[string]string{}
	}
	values, err := app.ResolveValues(input, record.Values)
	if err != nil {
		return nil, err
	}
	data, err := m.catalog.ComposeFile(app.ID, arch)
	if err != nil {
		return nil, err
	}
	record.Version, record.Port, record.Values = app.Version, port, values
	record.UpdatedAt = time.Now().UTC()
	return &Plan{App: app, Record: record, Fresh: fresh, compose: data}, nil
}

// portOwner returns the name of a container (outside project) publishing
// port on the host, if any.
func (m *Manager) portOwner(ctx context.Context, port int, project string) (string, error) {
	list, err := m.engine.ListContainers(ctx, engine.ListContainersOptions{})
	if err != nil {
		return "", err
	}
	for _, c := range list {
		if c.Labels[projectLabel] == project {
			continue
		}
		for _, p := range c.Ports {
			if int(p.PublicPort) == port {
				return c.Name(), nil
			}
		}
	}
	return "", nil
}

// Environment returns every variable an app's template is rendered with.
// Host-provided variables take precedence over form values.
func (m *Manager) Environment(record Record) map[string]string {
	env := maps.Clone(record.Values)
	if env == nil {
		env = map[string]string{}
	}
	port := strconv.Itoa(record.Port)
	maps.Copy(env, map[string]string{
		"APP_ID":            record.ID,
		"APP_PORT":          port,
		"APP_DATA_DIR":      m.dir(record.ID),
		"APP_HOST":          m.settings.Host,
		"APP_DOMAIN":        net.JoinHostPort(m.settings.Host, port),
		"APP_PROTOCOL":      "http",
		"APP_EXPOSED":       "false",
		"LOCAL_DOMAIN":      m.settings.LocalDomain,
		"ROOT_FOLDER_HOST":  m.settings.StorageDir,
		"TZ":                m.settings.Timezone,
		"DNS_IP":            m.settings.DNSIP,
		"INTERNAL_IP":       m.settings.Host,
		"NETWORK_INTERFACE": m.settings.NetworkInterface,
	})
	return env
}

func (m *Manager) project(record Record) compose.Project {
	env := m.Environment(record)
	list := make([]string, 0, len(env))
	for _, key := range slices.Sorted(maps.Keys(env)) {
		list = append(list, key+"="+env[key])
	}
	dir := m.dir(record.ID)
	files := []string{filepath.Join(dir, composeFile), filepath.Join(dir, runtimeFile)}
	return compose.Project{Name: record.ID, Dir: dir, Files: files, Env: list}
}

// Apply writes the app's files and brings it up. A failed fresh install is
// rolled back so it can simply be retried.
func (m *Manager) Apply(ctx context.Context, plan *Plan, out func(string)) error {
	record := plan.Record
	dir := m.dir(record.ID)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	err := m.apply(ctx, plan, out)
	if err != nil && plan.Fresh {
		out("Install failed, rolling back")
		// Use a fresh context: ctx may be the reason we failed.
		cleanup, cancel := context.WithTimeout(context.WithoutCancel(ctx), 2*time.Minute)
		defer cancel()
		if downErr := m.cli.Down(cleanup, m.project(record), true, out); downErr != nil {
			out("Rollback: " + downErr.Error())
		}
		os.RemoveAll(dir)
	}
	return err
}

func (m *Manager) apply(ctx context.Context, plan *Plan, out func(string)) error {
	record := plan.Record
	dir := m.dir(record.ID)
	if err := m.seed(record.ID, dir, out); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, composeFile), plan.compose, 0o644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, runtimeFile), []byte(runtimeCompose), 0o644); err != nil {
		return err
	}
	env := m.Environment(record)
	// COMPOSE_FILE lets the plain CLI pick up both files from the app directory.
	env["COMPOSE_FILE"] = composeFile + ":" + runtimeFile
	if err := writeEnvFile(filepath.Join(dir, envFile), env); err != nil {
		return err
	}
	if err := writeRecord(filepath.Join(dir, recordFile), record); err != nil {
		return err
	}
	if app := plan.App; app.UID != nil && app.GID != nil {
		chownData(filepath.Join(dir, "data"), *app.UID, *app.GID, out)
	}
	opts := compose.UpOptions{}
	if plan.App.ForcePull {
		opts.Pull = "always"
	}
	if plan.Fresh {
		out(fmt.Sprintf("Installing %s %s on port %d", plan.App.Name, record.Version, record.Port))
	} else {
		out(fmt.Sprintf("Updating %s to %s", plan.App.Name, record.Version))
	}
	if err := m.cli.Up(ctx, m.project(record), opts, out); err != nil {
		return err
	}
	out("Done")
	return nil
}

// seed copies the template's seed files (data/, config/, ...) into dir
// without overwriting existing files, so user data survives updates.
func (m *Manager) seed(id, dir string, out func(string)) error {
	entries, err := m.catalog.SeedEntries(id)
	if err != nil {
		return err
	}
	src := m.catalog.Dir(id)
	for _, name := range entries {
		err := filepath.WalkDir(filepath.Join(src, name), func(p string, d fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			rel, _ := filepath.Rel(src, p)
			dst := filepath.Join(dir, rel)
			if d.IsDir() {
				return os.MkdirAll(dst, 0o755)
			}
			if _, err := os.Lstat(dst); err == nil {
				return nil
			}
			if d.Type()&fs.ModeSymlink != 0 {
				return nil // never follow links out of the catalog
			}
			return copyFile(p, dst)
		})
		if err != nil {
			return fmt.Errorf("seed %s: %w", name, err)
		}
	}
	if len(entries) > 0 {
		out("Prepared " + strings.Join(entries, ", "))
	}
	return nil
}

func copyFile(src, dst string) error {
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	info, err := in.Stat()
	if err != nil {
		return err
	}
	f, err := os.OpenFile(dst, os.O_WRONLY|os.O_CREATE|os.O_EXCL, info.Mode().Perm())
	if err != nil {
		return err
	}
	if _, err := io.Copy(f, in); err != nil {
		f.Close()
		return err
	}
	return f.Close()
}

// chownData hands the data directory to the uid/gid the app runs as. It
// needs root; otherwise it is skipped with a note.
func chownData(dir string, uid, gid int, out func(string)) {
	if os.Geteuid() != 0 {
		out(fmt.Sprintf("Skipping chown of data to %d:%d (not running as root)", uid, gid))
		return
	}
	filepath.WalkDir(dir, func(p string, _ fs.DirEntry, err error) error {
		if err == nil {
			os.Lchown(p, uid, gid)
		}
		return nil
	})
}

func writeRecord(path string, record Record) error {
	data, err := json.MarshalIndent(record, "", "  ")
	if err != nil {
		return err
	}
	return writeFileAtomic(path, append(data, '\n'), 0o600)
}

// writeEnvFile writes a dotenv file so the plain compose CLI works in the
// app directory. The panel itself also passes every variable through the
// process environment, which compose gives precedence over .env. Values are
// single quoted (literal); values containing quotes or newlines are double
// quoted with escapes.
func writeEnvFile(path string, env map[string]string) error {
	var b strings.Builder
	for _, key := range slices.Sorted(maps.Keys(env)) {
		b.WriteString(key + "=" + quoteEnv(env[key]) + "\n")
	}
	return writeFileAtomic(path, []byte(b.String()), 0o600)
}

func quoteEnv(v string) string {
	if !strings.ContainsAny(v, "'\n\r") {
		return "'" + v + "'"
	}
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`, "\r", `\r`, "$", "$$")
	return `"` + r.Replace(v) + `"`
}

func writeFileAtomic(path string, data []byte, perm os.FileMode) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), "."+filepath.Base(path)+".*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Chmod(perm); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}

// Action is a lifecycle operation on an installed app.
type Action string

const (
	ActionStart   Action = "start"
	ActionStop    Action = "stop"
	ActionRestart Action = "restart"
)

// Do runs a lifecycle action. Start uses `up` so it also recreates
// containers that were removed.
func (m *Manager) Do(ctx context.Context, id string, action Action, out func(string)) error {
	record, err := m.readRecord(id)
	if err != nil {
		return err
	}
	p := m.project(*record)
	switch action {
	case ActionStart:
		return m.cli.Up(ctx, p, compose.UpOptions{}, out)
	case ActionStop, ActionRestart:
		return m.cli.Run(ctx, p, out, string(action))
	}
	return fmt.Errorf("unsupported app action %q", action)
}

// Uninstall removes an app's containers and files. With keepData the data
// directory and named volumes are preserved, so reinstalling picks them up.
func (m *Manager) Uninstall(ctx context.Context, id string, keepData bool, out func(string)) error {
	record, err := m.readRecord(id)
	if err != nil {
		return err
	}
	if err := m.cli.Down(ctx, m.project(*record), !keepData, out); err != nil {
		return err
	}
	dir := m.dir(id)
	if !keepData {
		out("Removing " + dir)
		return os.RemoveAll(dir)
	}
	for _, name := range []string{composeFile, runtimeFile, envFile, recordFile} {
		if err := os.Remove(filepath.Join(dir, name)); err != nil && !os.IsNotExist(err) {
			return err
		}
	}
	out("Kept data in " + dir)
	return nil
}
