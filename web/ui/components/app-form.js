import { html, useRef, useState } from '../lib/html.js';
import { Field, Notice, Badge } from '../lib/ui.js';
import { usePanel } from '../lib/panel.js';
import { startJob } from '../docker.js';

const inputTypes = { email: 'email', url: 'url', number: 'number', password: 'password' };

// initialValues pre-fills the form from current values, then defaults.
export function initialValues(fields, current = {}) {
  const values = {};
  for (const f of fields) {
    if (f.type === 'random') continue;
    const fallback = f.default !== undefined ? String(f.default) : f.type === 'boolean' ? 'false' : '';
    values[f.env_variable] = current[f.env_variable] ?? fallback;
  }
  return values;
}

function SecretInput({ value, onInput, required, minLength, maxLength }) {
  const [shown, setShown] = useState(false);
  return html`<div class="list-input-row">
    <input class="input mono" type=${shown ? 'text' : 'password'} autocomplete="new-password"
      value=${value} onInput=${onInput} required=${required} minLength=${minLength} maxLength=${maxLength} />
    <button type="button" class="button" onClick=${() => setShown(s => !s)}>${shown ? 'Hide' : 'Show'}</button>
  </div>`;
}

// AppForm renders an app's install form. Random fields are generated by
// the server and not asked for.
export function AppForm({ fields, values, errors = {}, onChange }) {
  const set = key => e => onChange({ ...values, [key]: e.target.type === 'checkbox' ? String(e.target.checked) : e.target.value });
  return fields.filter(f => f.type !== 'random').map(f => {
    const key = f.env_variable;
    const value = values[key] ?? '';
    const common = { required: f.required, value, onInput: set(key) };
    let control;
    if (f.options?.length) {
      control = html`<select class="input" ...${common} onChange=${set(key)}>
        ${f.required ? null : html`<option value="">—</option>`}
        ${f.options.map(o => html`<option value=${o.value}>${o.label}</option>`)}
      </select>`;
    } else if (f.type === 'boolean') {
      control = html`<label class="field-check"><input type="checkbox" checked=${value === 'true'} onChange=${set(key)} />Enable</label>`;
    } else if (f.type === 'password') {
      control = html`<${SecretInput} ...${common} minLength=${f.min} maxLength=${f.max} />`;
    } else {
      const numeric = f.type === 'number';
      control = html`<input class="input" type=${inputTypes[f.type] || 'text'} placeholder=${f.placeholder || ''} ...${common}
        min=${numeric ? f.min : undefined} max=${numeric ? f.max : undefined}
        minLength=${numeric ? undefined : f.min} maxLength=${numeric ? undefined : f.max} />`;
    }
    return html`<${Field} key=${key} label=${f.label} required=${f.required} hint=${f.hint} error=${errors[key]}>${control}<//>`;
  });
}

// DomainField publishes the app at its own HTTPS domain through the panel's
// reverse proxy; empty keeps it on host:port only.
export function DomainField({ value, onChange, error }) {
  return html`<${Field} label="Domain" error=${error} hint="Publish over HTTPS through the gateway, such as notes.example.com; empty for the port only">
    <input class="input" value=${value} placeholder="app.example.com" onInput=${e => onChange(e.target.value)} /><//>`;
}

export function InstallForm({ app, exposable, submitting, setSubmitting, onDone }) {
  const { api } = usePanel();
  const [values, setValues] = useState(() => initialValues(app.form_fields));
  const [port, setPort] = useState(app.port || '');
  const [domain, setDomain] = useState('');
  const [errors, setErrors] = useState({});
  const [error, setError] = useState(null);
  const pending = useRef(false);
  const generated = app.form_fields.filter(f => f.type === 'random');
  const submit = async e => {
    e.preventDefault();
    if (pending.current) return;
    pending.current = true;
    setErrors({});
    setError(null);
    setSubmitting(true);
    try {
      await startJob(api, () => api.installApp(app.id, { port: Number(port) || 0, values, ...(domain ? { domain } : {}) }), {
        onDone,
      });
    } catch (err) {
      setErrors(err.fields || {});
      setError(err.fields && Object.keys(err.fields).length ? null : err);
    } finally {
      pending.current = false;
      setSubmitting(false);
    }
  };
  return html`<form id="app-install" class="form card" onSubmit=${submit}>
    <h2>Install</h2>
    <${Notice} error=${error} />
    <fieldset class="form-fields" disabled=${submitting}>
    ${app.port ? html`<${Field} label="Port" required hint="The port the app listens on on the host" error=${errors.port}>
      <input class="input" type="number" min="1" max="65535" required value=${port} onInput=${e => setPort(e.target.value)} /><//>` : null}
    ${exposable ? html`<${DomainField} value=${domain} onChange=${setDomain} error=${errors.domain} />` : null}
    <${AppForm} fields=${app.form_fields} values=${values} errors=${errors} onChange=${setValues} />
    ${generated.length ? html`<div class="field-hint">Generated for you: ${generated.map(f => html`<${Badge}>${f.label}<//> `)}</div>` : null}
    </fieldset>
    <div class="button-actions"><button class="button button-primary" disabled=${submitting}>Install ${app.name}</button></div>
  </form>`;
}
